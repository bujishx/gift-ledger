"""Temporary bounded observer invoked by the DSM consumer; never a daemon.

CONFIG is generated by the matching one-time controller. This file on its own
is inert. No Docker, notification, network or service commands are executed.
"""
import json
import os
from pathlib import Path
import re
import signal
import stat
import sys
import time

CONFIG = None


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('duplicate_field')
        result[key] = value
    return result


def process_stat(raw):
    closing = raw.rfind(')')
    if closing < 1:
        raise ValueError('invalid_process_stat')
    fields = raw[closing + 1:].split()
    return {'pid': int(raw.split(' ', 1)[0]), 'parent': int(fields[1]),
            'start_ticks': int(fields[19])}


def same_producer(epoch):
    parent = os.getppid()
    for _ in range(4):
        if parent < 1:
            return False
        folder = Path('/proc') / str(parent)
        value = process_stat((folder / 'stat').read_text(encoding='ascii'))
        if parent == epoch['pid']:
            return (value['start_ticks'] == epoch['start_ticks'] and
                    str((folder / 'exe').resolve(strict=True)) == epoch['executable'])
        parent = value['parent']
    return False


def classify(raw, config, now_ns):
    if not isinstance(config, dict) or len(raw.encode('utf-8')) > 65536:
        return None
    if not config['not_before_ns'] <= now_ns <= config['deadline_ns']:
        return None
    event = json.loads(raw, object_pairs_hook=unique)
    if not isinstance(event, dict) or event.get('Type') != 'container':
        return None
    actor = event.get('Actor')
    if not isinstance(actor, dict) or not isinstance(actor.get('Attributes'), dict):
        return None
    attributes = actor['Attributes']
    identity = actor.get('ID')
    name = attributes.get('name')
    if not isinstance(identity, str) or not re.fullmatch('[0-9a-f]{64}', identity):
        return None
    if event.get('id', identity) != identity:
        return None
    event_ns = event.get('timeNano')
    if type(event_ns) is not int or not config['not_before_ns'] <= event_ns <= now_ns + 5_000_000_000:
        return None
    kind = None
    if event.get('Action') == 'die' and identity == config['web_id'] and name == config['web_name']:
        kind = 'die'
    elif event.get('Action') in ('create', 'destroy') and attributes.get(config['label']) == config['nonce']:
        for role in ('initial', 'after'):
            if name == config['marker_names'][role]:
                kind = role if event['Action'] == 'create' else role + '_destroy'
    if kind is None:
        return None
    return {'format': 'gift-ledger-s1-consumer-event-ack-v1', 'kind': kind,
            'actor_id': identity, 'actor_name': name, 'event_time_ns': event_ns,
            'observed_time_ns': now_ns, 'nonce': config['nonce'], 'epoch': config['epoch']}


def enabled_value(path):
    fd = os.open(str(path), os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, 'rb') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_size > 65536 or info.st_uid != 0:
            raise ValueError('profile_file_invalid')
        raw = stream.read(65537)
    value = json.loads(raw, object_pairs_hook=unique).get('enabled')
    if type(value) is not bool:
        raise ValueError('enabled_boolean_required')
    return value


def exclusive_receipt(directory, receipt):
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError('report_directory_invalid')
    info = directory.stat()
    if info.st_uid != 0 or info.st_mode & 0o022:
        raise ValueError('report_directory_owner_or_mode')
    if receipt['kind'] not in ('initial', 'die', 'after', 'initial_destroy', 'after_destroy'):
        raise ValueError('receipt_kind_invalid')
    target = directory / (receipt['kind'] + '.json')
    pending = directory / ('.' + receipt['kind'] + '.pending')
    raw = (json.dumps(receipt, sort_keys=True) + '\n').encode('ascii')
    try:
        fd = os.open(str(pending), os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644)
    except FileExistsError:
        return  # Preserve the first matching event, never overwrite or append.
    with os.fdopen(fd, 'wb') as stream:
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())
    try:
        os.link(str(pending), str(target))  # Atomic publication, no overwrite.
    except FileExistsError:
        pass
    pending.unlink()


def observe(raw, config, producer=same_producer, enabled=enabled_value,
            writer=exclusive_receipt, now=time.time_ns, monotonic=time.monotonic_ns):
    receipt = classify(raw, config, now())
    if receipt is None:
        return False
    receipt['observed_monotonic_ns'] = monotonic()
    if not producer(config['epoch']):
        receipt['producer_verified'] = False
    else:
        receipt['producer_verified'] = True
    if receipt['kind'] == 'die':
        receipt['enabled_at_hook'] = enabled(Path(config['profile_path']))
    writer(Path(config['receipt_directory']), receipt)
    return receipt['producer_verified']


if __name__ == '__main__':
    # A malformed/unrelated event or failed observation must never inhibit the
    # vendor's following notification handler. The controller checks receipts.
    try:
        if CONFIG is not None and len(sys.argv) == 2:
            # Bound only this short-lived observer, never the vendor process.
            import resource
            resource.setrlimit(resource.RLIMIT_AS, (128 * 1024**2, 128 * 1024**2))
            resource.setrlimit(resource.RLIMIT_CPU, (2, 2))
            def expired(signum, frame):
                raise TimeoutError('observer_deadline')
            signal.signal(signal.SIGALRM, expired)
            signal.alarm(3)
            observe(sys.argv[1], CONFIG)
    except Exception:
        pass
    raise SystemExit(0)
